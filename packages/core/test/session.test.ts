// Marqueur de session (§3.6, #160, #169) : reconnaissance sur toute ligne où il est seul,
// neutralité de la métadonnée pour la validation (§3.5), les exemptions (§4.2) et le critère 2
// (§6.2.1), et le marqueur en double.

import { describe, expect, it } from 'vitest';
import { extractSessionMarker } from '../src/session.js';
import { analyze, isBlocking, validate } from '../src/validator.js';
import { defaultConfig } from '../src/config/defaults.js';
import { parseConfigDocument } from '../src/config/schema.js';
import { codes, config, vInput } from './helpers.js';
import { resolveConfig } from '../src/config/resolve.js';
import { isCompliant } from '../src/validator.js';

const value = (body: string) => extractSessionMarker(body)?.value ?? null;

describe('CA-51 — reconnaissance du marqueur de session (§3.6)', () => {
  it('reconnu en dernière ligne, avec zéro, une ou plusieurs lignes blanches après', () => {
    const body = 'issue (blocking): titre\n\nDétail.\n\n[session:Melancholy-Coordinated-Value-Object]';
    expect(value(body)).toBe('Melancholy-Coordinated-Value-Object');
    expect(value(`${body}\n`)).toBe('Melancholy-Coordinated-Value-Object');
    expect(value(`${body}\n\n  \n\t\n`)).toBe('Melancholy-Coordinated-Value-Object');
    expect(value(`${body}\r\n\r\n`)).toBe('Melancholy-Coordinated-Value-Object');
  });

  it('toute valeur libre non vide ; aucun GUID exigé ; casse et blancs internes conservés', () => {
    expect(value('note: x\n[session:run 42]')).toBe('run 42');
    expect(value('note: x\n[session:3f2b0c1e-9d4a-4c55-8e0a-0b6f1d2c3e4f]')).toBe('3f2b0c1e-9d4a-4c55-8e0a-0b6f1d2c3e4f');
    expect(value('note: x\n[session:  Spaced  ]')).toBe('Spaced');
    expect(value('note: x\n[session:a]b]')).toBe('a]b');
    expect(value('note: x\n   [session:indented]   ')).toBe('indented');
  });

  it('une description entre parenthèses termine la valeur : identifiant et description séparés, casse gardée', () => {
    const m = extractSessionMarker(
      "note: x\n[session:Disheartening-Reviewed-Implementation(On a passé l'implémentation en revue, et franchement !)]"
    )!;
    expect(m.value).toBe('Disheartening-Reviewed-Implementation');
    expect(m.description).toBe("On a passé l'implémentation en revue, et franchement !");
    expect(m.lines[0]!.raw).toBe(
      "[session:Disheartening-Reviewed-Implementation(On a passé l'implémentation en revue, et franchement !)]"
    );
    expect(m.contentBody).toBe('note: x');
    // Blancs de bordure retirés des deux côtés ; la première `(` sépare, la dernière `)` ferme.
    const spaced = extractSessionMarker('note: x\n[session: run-1 ( texte (avec) parenthèses ] ) ]')!;
    expect([spaced.value, spaced.description]).toEqual(['run-1', 'texte (avec) parenthèses ]']);
  });

  it('sans identifiant ou sans description, ou suivie d’autre chose, la valeur reste un identifiant entier', () => {
    for (const v of ['run-1()', 'run-1(  )', '(texte)', 'run-1(texte) suite', 'run-1(texte']) {
      const m = extractSessionMarker(`note: x\n[session:${v}]`)!;
      expect([m.value, m.description]).toEqual([v, null]);
    }
    expect(extractSessionMarker('note: x\n[session:run-1]')!.description).toBeNull();
  });

  it('la ligne brute est gardée telle qu’écrite, et le corps sans elle est exact au caractère près', () => {
    const m = extractSessionMarker('note: x\r\n\r\n  [session:Run-7]  \r\n')!;
    expect(m.lines).toEqual([{ raw: '[session:Run-7]', value: 'Run-7', description: null }]);
    expect(m.contentBody).toBe('note: x\r\n\r\n');
  });

  it('reconnu sur n’importe quelle ligne où il est seul : un pied de signature peut le suivre (#169)', () => {
    const signed = 'done: corrigé\n\nDétail.\n\n[session:run-1]\n\n---\n_Generated by a tool_';
    expect(value(signed)).toBe('run-1');
    expect(extractSessionMarker(signed)!.contentBody).toBe('done: corrigé\n\nDétail.\n\n\n---\n_Generated by a tool_');
    expect(value('note: x\n[session:a]\n\nencore du texte')).toBe('a');
  });

  it('retiré avec sa fin de ligne, où qu’il soit, et rien d’autre ne bouge', () => {
    expect(extractSessionMarker('note: x\n[session:a]\nsuite')!.contentBody).toBe('note: x\nsuite');
    expect(extractSessionMarker('[session:a]\r\nnote: x')!.contentBody).toBe('note: x');
    expect(extractSessionMarker('note: x\n[session:a]')!.contentBody).toBe('note: x');
    expect(extractSessionMarker('[session:a]')!.contentBody).toBe('');
  });

  it.each([
    ['valeur vide', 'note: x\n[session:]'],
    ['valeur blanche', 'note: x\n[session:   ]'],
    ['en ligne avec du texte', 'note: x\nfin [session:a]'],
    ['suivi de texte', 'note: x\n[session:a] fin'],
    ['dans un bloc de code délimité', 'note: x\n```\n[session:a]\n```'],
    ['dans un bloc de code jamais refermé', 'note: x\n```\n[session:a]'],
    ['dans une citation', 'note: x\n> [session:a]'],
    ['mot-clé dans une autre casse', 'note: x\n[Session:a]'],
    ['espace avant le deux-points', 'note: x\n[session :a]'],
    ['crochet fermant absent', 'note: x\n[session:a'],
    ['corps vide', ''],
  ])('non reconnu : %s', (_name, body) => {
    expect(extractSessionMarker(body)).toBeNull();
  });

  it('un marqueur mal formé ou mal placé reste du texte ordinaire : aucun diagnostic nouveau', () => {
    // En ligne avec du texte, la ligne compte comme discussion : aucun W-NO-DISCUSSION.
    expect(codes(validate(vInput('issue: titre conforme\nvoir [session:a]'), config()))).toEqual([]);
    // Seul dans le corps mais mal formé : c'est la ligne de préfixe, comme toute phrase.
    expect(codes(validate(vInput('[session:]'), config()))).toEqual(['E-NO-LABEL']);
  });

  it('au-dessus de la ligne de préfixe, il est retiré avant elle : même verdict que tout en bas', () => {
    for (const body of ['issue: le nom est ambigu', 'issue: titre conforme\n\nDétail.', 'isue: x', 'suggestion (blocking: x']) {
      const above = analyze(vInput(`[session:run-1]\n${body}`), config());
      const below = analyze(vInput(`${body}\n\n[session:run-1]`), config());
      expect(above.prefixLine).toBe(below.prefixLine);
      expect(above.diagnostics).toEqual(below.diagnostics);
      expect(above.resolved?.label.id).toBe(below.resolved?.label.id);
      expect(above.session?.value).toBe('run-1');
    }
  });
});

describe('CA-52 — la métadonnée ne satisfait aucune exigence et ne change aucun effet (§3.6)', () => {
  it('ne compte pas comme discussion : W-NO-DISCUSSION subsiste sur un commentaire bloquant', () => {
    expect(codes(validate(vInput('issue: le nom est ambigu'), config()))).toEqual(['W-NO-DISCUSSION']);
    expect(codes(validate(vInput('issue: le nom est ambigu\n\n[session:run-1]'), config()))).toEqual([
      'W-NO-DISCUSSION',
    ]);
  });

  it('ne devient jamais la ligne de préfixe, ni le sujet', () => {
    const a = analyze(vInput('issue:\n[session:run-1]'), config());
    expect(a.prefixLine).toBe('issue:');
    expect(codes(a.diagnostics)).toEqual(['E-EMPTY-SUBJECT', 'W-NO-DISCUSSION']);
    expect(a.session?.value).toBe('run-1');
  });

  it('seul dans le corps, il ne fait pas un commentaire : corps sans contenu, exempté comme un corps vide (§4.2)', () => {
    const a = analyze(vInput('[session:run-1]\n'), config());
    expect(a.outcome).toBe('exempt');
    expect(a.diagnostics).toEqual([]);
    expect(a.resolved).toBeNull();
    expect(a.session?.value).toBe('run-1');
  });

  it('n’est pas du contenu pour allowlistPatterns, appliquées au corps sans lui', () => {
    const cfg = config((c) => (c.allowlistPatterns = ['^LGTM$']));
    expect(analyze(vInput('LGTM\n\n[session:run-1]'), cfg).outcome).toBe('exempt');
  });

  it('ne change ni le label, ni les décorations, ni le caractère bloquant', () => {
    for (const body of ['issue: fuite mémoire\n\ndétail', 'note (non-blocking): rien\n\ndétail', 'praise: bien']) {
      const without = analyze(vInput(body), config());
      const withMarker = analyze(vInput(`${body}\n\n[session:run-1]`), config());
      expect(withMarker.resolved?.label.id).toBe(without.resolved?.label.id);
      expect(withMarker.decorations).toEqual(without.decorations);
      expect(withMarker.blocking).toBe(without.blocking);
      expect(isBlocking(vInput(`${body}\n\n[session:run-1]`), config())).toBe(without.blocking);
    }
  });

  it('la clôture par `decision` est inchangée : une réponse `decision` portant un marqueur reste une décision', () => {
    const reply = (body: string) => analyze(vInput(body, { zone: 'reply' }), config());
    const decision = reply('decision: on garde, le coût de la migration dépasse le gain\n\n[session:b]');
    expect(decision.resolved?.label.id).toBe('decision');
    expect(decision.diagnostics).toEqual([]);
    // Le marqueur ne prête pas au motif la longueur qui lui manque (§6.1.1, E-DECISION-SUBJECT).
    expect(codes(reply('decision: trop court\n\n[session:une-tres-longue-valeur-de-session]').diagnostics)).toContain(
      'E-DECISION-SUBJECT'
    );
  });
});

describe('`sessionIcon` — présentation seule (§8.2)', () => {
  it('robot par défaut, surchargeable, chaîne non vide', () => {
    expect(defaultConfig().sessionIcon).toBe('\u{1F916}');
    const ok = parseConfigDocument(JSON.stringify({ sessionIcon: '\u{1F9ED}' }), { level: 'repo' });
    expect(ok.values?.['sessionIcon']).toBe('\u{1F9ED}');
    expect(ok.notices).toEqual([]);
    // Même règle que `badgeStyle` : une valeur du mauvais type rend le document invalide (§8.1.5).
    const bad = parseConfigDocument(JSON.stringify({ sessionIcon: '' }), { level: 'repo' });
    expect(bad.invalid).toBe(true);
  });
});

describe('CA-54 — marqueur en double (§3.6)', () => {
  it('plusieurs marqueurs : aucune session désignée, toutes les lignes retirées du corps', () => {
    const m = extractSessionMarker('note: x\n[session:a]\n\nDétail.\n[session:b]\n')!;
    expect(m.value).toBeNull();
    expect(m.lines.map((l) => l.value)).toEqual(['a', 'b']);
    expect(m.contentBody).toBe('note: x\n\nDétail.\n');
    // Même valeur deux fois : c'est encore un doublon.
    expect(extractSessionMarker('note: x\n[session:a]\n[session:a]')!.value).toBeNull();
    // Les descriptions ne départagent rien : aucune n'est retenue.
    const described = extractSessionMarker('note: x\n[session:a(un)]\n[session:a(deux)]')!;
    expect([described.value, described.description]).toEqual([null, null]);
  });

  it('W-SESSION-MULTIPLE, un avertissement, en dernier dans la liste, et rien d’autre ne change', () => {
    const body = 'issue: le nom est ambigu\n\nDétail.\n\n[session:a]\n[session:b]';
    const a = analyze(vInput(body), config());
    expect(a.diagnostics.map((d) => [d.code, d.severity])).toEqual([['W-SESSION-MULTIPLE', 'warn']]);
    expect(a.diagnostics[0]!.message).toContain('2');
    expect(a.blocking).toBe(analyze(vInput('issue: le nom est ambigu\n\nDétail.'), config()).blocking);
    // Rangé après les contrôles de contenu, comme le tableau du §3.5.2.
    expect(codes(validate(vInput('isue: x\n[session:a]\n[session:b]'), config()))).toEqual([
      'E-UNKNOWN-LABEL',
      'W-SESSION-MULTIPLE',
    ]);
  });

  it('jamais une erreur, même demandée par `severities` — dépôt ou plancher : un avertissement, signalé (§3.6, §8.2)', () => {
    const doc = { status: 'found', text: JSON.stringify({ severities: { 'W-SESSION-MULTIPLE': 'error' } }) } as const;
    for (const [floor, repo] of [
      [null, doc],
      [{ severities: { 'W-SESSION-MULTIPLE': 'error' } }, { status: 'absent' } as const],
    ] as const) {
      const { config: resolved, notices } = resolveConfig(floor as never, { status: 'absent' }, repo);
      expect(resolved.severities['W-SESSION-MULTIPLE']).toBe('warn');
      expect(notices.some((n) => n.ref === 'severities.W-SESSION-MULTIPLE')).toBe(true);
      const diagnostics = validate(vInput('note: titre conforme\n\n[session:a]\n[session:b]'), resolved);
      expect(diagnostics.map((d) => [d.code, d.severity])).toEqual([['W-SESSION-MULTIPLE', 'warn']]);
      expect(isCompliant(diagnostics)).toBe(true);
    }
    // Défense en profondeur : une configuration qui n'est pas passée par la résolution.
    const raw = config((c) => (c.severities = { 'W-SESSION-MULTIPLE': 'error' }));
    expect(isCompliant(validate(vInput('note: titre conforme\n[session:a]\n[session:b]'), raw))).toBe(true);
    // L'éteindre reste permis.
    const off = config((c) => (c.severities = { 'W-SESSION-MULTIPLE': 'off' }));
    expect(validate(vInput('note: titre conforme\n[session:a]\n[session:b]'), off)).toEqual([]);
  });

  it('jamais une erreur par défaut : un commentaire conforme le reste', () => {
    const diagnostics = validate(vInput('note: titre conforme\n\n[session:a]\n[session:b]'), config());
    expect(diagnostics.every((d) => d.severity === 'warn')).toBe(true);
  });

  it('dû seulement quand le commentaire est jugé : exempté ou zone éteinte, aucun diagnostic', () => {
    expect(analyze(vInput('[session:a]\n[session:b]'), config()).diagnostics).toEqual([]);
    const reply = analyze(vInput('done: ok\n[session:a]\n[session:b]', { zone: 'reply' }), config());
    expect(reply.outcome).toBe('excluded');
    expect(reply.diagnostics).toEqual([]);
    expect(reply.session?.value).toBeNull();
  });

  it('un seul marqueur : aucun W-SESSION-MULTIPLE', () => {
    expect(codes(validate(vInput('note: titre conforme\n\n[session:a]'), config()))).toEqual([]);
  });
});
