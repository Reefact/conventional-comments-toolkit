// Retire le pied d'attribution que pose une session Claude Code : de la description d'une PR,
// et d'un commentaire quand un marqueur de session le remplace. Isolé du workflow
// `strip-claude-footer.yml` pour être testé (tests/claude-footer.test.ts).
//
// DESCRIPTIONS — décision du propriétaire (2026-11-10) : elles ne portent pas ce pied. Une
// règle de CLAUDE.md n'y suffit pas — mesuré sur la PR #167 : la session a envoyé une
// description sans pied, et l'outil de CRÉATION de PR en a posé un au passage. Modifier une
// description par l'outil, en revanche, n'en ajoute pas (mesuré sur #165). Le pied ne peut
// donc être retiré qu'APRÈS la création, par un chemin où l'outil n'intervient pas.
//
// COMMENTAIRES — seulement quand la ligne qui précède le pied est un marqueur de session
// (§3.6) : le marqueur dit alors qui a écrit (une session, pas le titulaire du compte), et le
// pied le répète. Sans marqueur, rien ne le dirait plus : le pied reste.
//
// Ce retrait avait une seconde raison, que #169 a levée : le §3.6 n'exige plus le marqueur en
// DERNIÈRE ligne. Un marqueur suivi du pied est reconnu par l'extension, pied en place ou non ;
// le retirer ne fait plus que rendre au commentaire la forme que les skills recommandent.
//
// Deux formes rencontrées, toutes deux en fin de texte, parfois l'une après l'autre :
//   - celle qu'écrit la session dans une description :
//       🤖 Generated with [Claude Code](https://claude.com/claude-code)
//
//       https://claude.ai/code/session_…        (le lien de session est facultatif)
//     Le lien n'est retiré qu'à la suite de cette ligne, jamais seul.
//   - celle que pose l'outil (descriptions, commentaires) :
//       ---
//       _Generated by [Claude Code](https://claude.ai/code/session_…)_
//
// Seule la FIN du texte est examinée : la même phrase citée au milieu (comme ici) reste.

const TRAILERS = [
  // Forme de l'outil : règle horizontale, puis la ligne en italique.
  /(?:^|\n)[ \t]*---[ \t]*\n+[ \t]*_Generated by \[Claude Code\]\([^)\s]*\)_[ \t]*$/u,
  // Forme de la session, lien de session compris s'il suit. Un lien de session SEUL n'est
  // pas un pied : c'est peut-être une référence voulue (« voir la session d'origine : … »),
  // et rien ne permet de distinguer les deux. Il reste (revue de la PR #167).
  /(?:^|\n)[ \t]*🤖 Generated with \[Claude Code\]\([^)\s]*\)[ \t]*(?:\n+[ \t]*https:\/\/claude\.ai\/code\/session_\S+[ \t]*)?$/u,
];

const TRAILING_WS = /\s+$/u;
const normalize = (text) => text.replace(/\r\n/g, '\n');

/** Le texte sans les pieds qui le terminent, blancs finaux retirés ; `null` s'il n'y en a pas. */
function withoutFooters(text) {
  let current = normalize(text);
  let stripped = false;
  for (;;) {
    const trimmed = current.replace(TRAILING_WS, '');
    const pattern = TRAILERS.find((candidate) => candidate.test(trimmed));
    if (!pattern) break;
    current = trimmed.replace(pattern, '');
    stripped = true;
  }
  return stripped ? current.replace(TRAILING_WS, '') : null;
}

/**
 * La description sans les pieds Claude Code qui la terminent.
 * Rend la chaîne d'entrée elle-même, intacte, quand il n'y a rien à retirer.
 * @param {string | null | undefined} body
 * @returns {string}
 */
export function stripClaudeFooter(body) {
  const original = body ?? '';
  return withoutFooters(original) ?? original;
}

// Reconnaissance du marqueur : copie de `extractSessionMarker()` (@cct/core, §3.6), que le
// workflow ne peut pas importer sans installer et construire le dépôt. Un test de parité la
// confronte à l'original (tests/claude-footer.test.ts) : c'est lui qui fait foi.
const FENCE_RE = /^\s*(`{3,}|~{3,})/;
const QUOTE_RE = /^\s*>/;
const EDGE = /^[\p{White_Space}\uFEFF]+|[\p{White_Space}\uFEFF]+$/gu;
const MARKER_RE = /^\[session:(.*)\]$/u;
const strip = (s) => s.replace(EDGE, '');

/**
 * Vrai si la dernière ligne non vide du texte est un marqueur de session (§3.6) : seule sur
 * sa ligne, hors bloc délimité et hors citation, valeur non vide.
 * @param {string} body
 * @returns {boolean}
 */
export function endsWithSessionMarker(body) {
  const lines = body.split(/\r?\n/);
  const discarded = new Set();
  let fence = null;
  for (let i = 0; i < lines.length; i++) {
    const m = FENCE_RE.exec(lines[i]);
    if (fence !== null) {
      discarded.add(i);
      if (m && m[1].startsWith(fence[0]) && m[1].length >= fence.length) fence = null;
      continue;
    }
    if (m) {
      fence = m[1];
      discarded.add(i);
    } else if (QUOTE_RE.test(lines[i])) {
      discarded.add(i);
    }
  }
  for (let i = lines.length - 1; i >= 0; i--) {
    const line = strip(lines[i]);
    if (line === '') continue;
    if (discarded.has(i)) return false;
    const m = MARKER_RE.exec(line);
    return m !== null && strip(m[1]) !== '';
  }
  return false;
}

/**
 * Le commentaire sans le pied Claude Code qui le termine, SEULEMENT si ce qui reste se
 * termine par un marqueur de session. Rend la chaîne d'entrée intacte sinon.
 * @param {string | null | undefined} body
 * @returns {string}
 */
export function stripClaudeFooterAfterSessionMarker(body) {
  const original = body ?? '';
  const stripped = withoutFooters(original);
  return stripped !== null && endsWithSessionMarker(stripped) ? stripped : original;
}
