// Retire de la description d'une PR le pied d'attribution que pose une session Claude Code.
// Isolé du workflow `strip-claude-footer.yml` pour être testé (tests/claude-footer.test.ts).
//
// Décision du propriétaire (2026-11-10) : les descriptions de PR ne portent pas ce pied.
// Une règle de CLAUDE.md n'y suffit pas — mesuré sur la PR #167 : la session a envoyé une
// description sans pied, et l'outil de CRÉATION de PR en a posé un au passage. Modifier une
// description par l'outil, en revanche, n'en ajoute pas (mesuré sur #165). Le pied ne peut
// donc être retiré qu'APRÈS la création, par un chemin où l'outil n'intervient pas.
//
// Deux formes rencontrées, toutes deux en fin de description, parfois l'une après l'autre :
//   - celle qu'écrit la session :
//       🤖 Generated with [Claude Code](https://claude.com/claude-code)
//
//       https://claude.ai/code/session_…        (le lien de session est facultatif)
//   - celle que pose l'outil de création :
//       ---
//       _Generated by [Claude Code](https://claude.ai/code/session_…)_
//
// Seule la FIN de la description est examinée : la même phrase citée au milieu d'un texte
// (comme ici) reste en place.

const TRAILERS = [
  // Forme de l'outil : règle horizontale, puis la ligne en italique.
  /(?:^|\n)[ \t]*---[ \t]*\n+[ \t]*_Generated by \[Claude Code\]\([^)\s]*\)_[ \t]*$/u,
  // Forme de la session, lien de session compris s'il suit.
  /(?:^|\n)[ \t]*🤖 Generated with \[Claude Code\]\([^)\s]*\)[ \t]*(?:\n+[ \t]*https:\/\/claude\.ai\/code\/session_\S+[ \t]*)?$/u,
  // Lien de session resté seul en dernière ligne.
  /(?:^|\n)[ \t]*https:\/\/claude\.ai\/code\/session_\S+[ \t]*$/u,
];

/**
 * La description sans les pieds Claude Code qui la terminent.
 * Rend la chaîne d'entrée elle-même, intacte, quand il n'y a rien à retirer.
 * @param {string | null | undefined} body
 * @returns {string}
 */
export function stripClaudeFooter(body) {
  const original = body ?? '';
  let text = original.replace(/\r\n/g, '\n');
  for (;;) {
    const trimmed = text.replace(/\s+$/u, '');
    const pattern = TRAILERS.find((candidate) => candidate.test(trimmed));
    if (!pattern) break;
    text = trimmed.replace(pattern, '');
  }
  const result = text.replace(/\s+$/u, '');
  return result === original.replace(/\r\n/g, '\n').replace(/\s+$/u, '') ? original : result;
}
