// Le retrait du pied Claude Code (`.github/workflows/strip-claude-footer.yml`), éprouvé sur les
// fins de texte réellement rencontrées : #165 (forme de la session) et #167 (forme posée par
// l'outil de création).
import { describe, expect, it } from 'vitest';
import { extractSessionMarker } from '@cct/core';
import {
  endsWithSessionMarker,
  stripClaudeFooter,
  stripClaudeFooterAfterSessionMarker,
} from '../scripts/lib/claude-footer.mjs';

const BODY = '## Checks\n\n`check:pr-scope`: documentation only.';
const SESSION = 'https://claude.ai/code/session_019k6GsTFFw5SmEGKBtGSif6';
const SESSION_FORM = `🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n${SESSION}`;
const TOOL_FORM = `---\n_Generated by [Claude Code](${SESSION})_`;

describe('stripClaudeFooter (descriptions)', () => {
  it('retire la forme écrite par la session, lien compris (#165)', () => {
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION_FORM}`)).toBe(BODY);
  });

  it('retire la forme écrite par la session sans lien (#162)', () => {
    const footer = '🤖 Generated with [Claude Code](https://claude.com/claude-code)';
    expect(stripClaudeFooter(`${BODY}\n\n${footer}`)).toBe(BODY);
  });

  it("retire la forme posée par l'outil de création (#167)", () => {
    expect(stripClaudeFooter(`${BODY}\n\n${TOOL_FORM}`)).toBe(BODY);
  });

  it("retire les deux formes quand l'outil ajoute la sienne après celle de la session", () => {
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION_FORM}\n\n${TOOL_FORM}`)).toBe(BODY);
  });

  it('retire un lien de session resté seul en dernière ligne, avec ou sans le pied après lui', () => {
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION}`)).toBe(BODY);
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION}\n\n${TOOL_FORM}`)).toBe(BODY);
  });

  it('garde un lien de session cité au milieu du texte', () => {
    const body = `See ${SESSION} for the original session.\n\nFin.`;
    expect(stripClaudeFooter(body)).toBe(body);
  });

  it('accepte les fins de ligne CRLF et les blancs finaux', () => {
    const crlf = `${BODY}\n\n${TOOL_FORM}\n\n`.replace(/\n/g, '\r\n');
    expect(stripClaudeFooter(crlf)).toBe(BODY);
  });

  it('rend la description intacte quand elle ne se termine pas par un pied', () => {
    const quoted = `Le pied « ${SESSION_FORM} » est retiré.\n\nFin.`;
    expect(stripClaudeFooter(quoted)).toBe(quoted);
    expect(stripClaudeFooter(BODY)).toBe(BODY);
  });

  it('laisse une règle horizontale qui ne précède pas le pied', () => {
    const body = `${BODY}\n\n---\n\nAnnexe.`;
    expect(stripClaudeFooter(body)).toBe(body);
  });

  it('rend une description vide quand elle ne contenait que le pied', () => {
    expect(stripClaudeFooter(TOOL_FORM)).toBe('');
    expect(stripClaudeFooter(null)).toBe('');
  });
});

describe('stripClaudeFooterAfterSessionMarker (commentaires)', () => {
  const REPLY = "done: JD025's summary is back on its own class in 51f5cde\n\nThe suite builds.";
  const MARKED = `${REPLY}\n\n[session:tedious-debated-branch]`;
  const COMMENT_FOOTER = '---\n_Generated by [Claude Code](https://claude.ai/code)_';

  it('retire le pied quand un marqueur de session le précède', () => {
    expect(stripClaudeFooterAfterSessionMarker(`${MARKED}\n\n${COMMENT_FOOTER}`)).toBe(MARKED);
  });

  it('rend au marqueur sa place de dernière ligne ; le cœur le reconnaît avec ou sans le pied (#169)', () => {
    const posted = `${MARKED}\n\n${COMMENT_FOOTER}`;
    expect(extractSessionMarker(posted)?.value).toBe('tedious-debated-branch');
    const stripped = stripClaudeFooterAfterSessionMarker(posted);
    expect(stripped.trimEnd().split('\n').pop()).toBe('[session:tedious-debated-branch]');
    expect(extractSessionMarker(stripped)?.value).toBe('tedious-debated-branch');
  });

  it('garde le pied quand aucun marqueur ne le précède', () => {
    const posted = `${REPLY}\n\n${COMMENT_FOOTER}`;
    expect(stripClaudeFooterAfterSessionMarker(posted)).toBe(posted);
  });

  it('garde le pied quand le marqueur est dans un bloc de code ou une citation', () => {
    for (const ending of ['```\n[session:x]\n```', '> [session:x]', '```\n[session:x]']) {
      const posted = `${REPLY}\n\n${ending}\n\n${COMMENT_FOOTER}`;
      expect(stripClaudeFooterAfterSessionMarker(posted)).toBe(posted);
    }
  });

  it('garde le pied quand le marqueur a une valeur vide', () => {
    const posted = `${REPLY}\n\n[session:  ]\n\n${COMMENT_FOOTER}`;
    expect(stripClaudeFooterAfterSessionMarker(posted)).toBe(posted);
  });

  it('retire un lien de session seul quand un marqueur le précède', () => {
    const posted = `${MARKED}\n\nhttps://claude.ai/code/session_xyz`;
    expect(stripClaudeFooterAfterSessionMarker(posted)).toBe(MARKED);
  });

  it('rend le commentaire intact quand il ne porte aucun pied', () => {
    expect(stripClaudeFooterAfterSessionMarker(MARKED)).toBe(MARKED);
    expect(stripClaudeFooterAfterSessionMarker(null)).toBe('');
  });
});

describe('endsWithSessionMarker : parité avec extractSessionMarker (@cct/core, §3.6)', () => {
  const cases = [
    '[session:abc]',
    'issue: x\n\n[session:abc]',
    'issue: x\n\n[session:abc]\n\n\n',
    'issue: x\r\n\r\n[session:abc]\r\n',
    'issue: x\n\n  [session:abc]  ',
    'issue: x\n\n[session:a]b]',
    'issue: x\n\n[session:]',
    'issue: x\n\n[session: \u00a0 ]',
    'issue: x\n\n[Session:abc]',
    'issue: x\n\n[session :abc]',
    'issue: x\n\ntext [session:abc]',
    'issue: x\n\n[session:abc] text',
    'issue: x\n\n> [session:abc]',
    'issue: x\n\n```\n[session:abc]\n```',
    'issue: x\n\n```\n[session:abc]',
    'issue: x\n\n~~~~\n```\n~~~~\n[session:abc]',
    'issue: x\n\n````\n```\n[session:abc]',
    'issue: x\n\n\uFEFF[session:abc]\u00a0',
    '',
    '\n\n',
  ];

  it.each(cases)('%j', (body) => {
    expect(endsWithSessionMarker(body)).toBe(extractSessionMarker(body) !== null);
  });
});
