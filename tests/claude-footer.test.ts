// Le retrait du pied Claude Code des descriptions de PR (`.github/workflows/strip-claude-footer.yml`),
// éprouvé sur les fins de description réellement rencontrées : #165 (forme de la session) et
// #167 (forme posée par l'outil de création).
import { describe, expect, it } from 'vitest';
import { stripClaudeFooter } from '../scripts/lib/claude-footer.mjs';

const BODY = '## Checks\n\n`check:pr-scope`: documentation only.';
const SESSION = 'https://claude.ai/code/session_019k6GsTFFw5SmEGKBtGSif6';
const SESSION_FORM = `🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n${SESSION}`;
const TOOL_FORM = `---\n_Generated by [Claude Code](${SESSION})_`;

describe('stripClaudeFooter', () => {
  it('retire la forme écrite par la session, lien compris (#165)', () => {
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION_FORM}`)).toBe(BODY);
  });

  it('retire la forme écrite par la session sans lien (#162)', () => {
    const footer = '🤖 Generated with [Claude Code](https://claude.com/claude-code)';
    expect(stripClaudeFooter(`${BODY}\n\n${footer}`)).toBe(BODY);
  });

  it("retire la forme posée par l'outil de création (#167)", () => {
    expect(stripClaudeFooter(`${BODY}\n\n${TOOL_FORM}`)).toBe(BODY);
  });

  it("retire les deux formes quand l'outil ajoute la sienne après celle de la session", () => {
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION_FORM}\n\n${TOOL_FORM}`)).toBe(BODY);
  });

  it('retire un lien de session resté seul en dernière ligne', () => {
    expect(stripClaudeFooter(`${BODY}\n\n${SESSION}`)).toBe(BODY);
  });

  it('accepte les fins de ligne CRLF et les blancs finaux', () => {
    const crlf = `${BODY}\n\n${TOOL_FORM}\n\n`.replace(/\n/g, '\r\n');
    expect(stripClaudeFooter(crlf)).toBe(BODY);
  });

  it('rend la description intacte quand elle ne se termine pas par un pied', () => {
    const quoted = `Le pied « ${SESSION_FORM} » est retiré.\n\nFin.`;
    expect(stripClaudeFooter(quoted)).toBe(quoted);
    expect(stripClaudeFooter(BODY)).toBe(BODY);
  });

  it('laisse une règle horizontale qui ne précède pas le pied', () => {
    const body = `${BODY}\n\n---\n\nAnnexe.`;
    expect(stripClaudeFooter(body)).toBe(body);
  });

  it('rend une description vide quand elle ne contenait que le pied', () => {
    expect(stripClaudeFooter(TOOL_FORM)).toBe('');
    expect(stripClaudeFooter(null)).toBe('');
  });
});
